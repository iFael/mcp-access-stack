#!/usr/bin/python3
"""Root-owned, fixed-scope Oracle APT maintenance. No user-selected packages or commands."""
import fcntl
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import time

WORKSPACE = "mcp-access-stack"
STATE = Path("/var/lib/mcp-v3-apt-maintenance")
HELPER = "/usr/local/libexec/mcp-v3-apt-maintenance.py"
PYTHON = "/usr/bin/python3"
APT = "/usr/bin/apt-get"
DPKG = "/usr/bin/dpkg"
QUERY = "/usr/bin/dpkg-query"
REPAIR = "repair_oracle_kernel_dependencies"
BROWSER = "install_browser_dependencies"
LIBRARIES = ("libcups2t64", "libcairo2", "libpango-1.0-0")
ENV = {"PATH": "/usr/sbin:/usr/bin:/sbin:/bin", "HOME": "/root",
       "LANG": "C", "LC_ALL": "C", "DEBIAN_FRONTEND": "noninteractive",
       "NEEDRESTART_SUSPEND": "1"}
FLAGS = ["--no-remove", "--no-upgrade", "--no-install-recommends"]
UUID = re.compile(r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}")
SHA = re.compile(r"[0-9a-f]{64}")
NAME = r"[a-z0-9][a-z0-9+.-]*(?::[a-z0-9-]+)?"
VERSION = r"[0-9][a-zA-Z0-9.+:~\-]*"
MODULE = re.compile(r"linux-modules-(\d+\.\d+\.\d+-\d+)-oracle")
KERNEL = re.compile(
    r"(?:linux-(?:image|modules(?:-extra)?|headers|tools)(?:-\d+\.\d+\.\d+-\d+)?-oracle"
    r"|linux-oracle(?:-\d+\.\d+-(?:headers|tools)-\d+\.\d+\.\d+-\d+)?)"
)
CHANGE = re.compile(
    rf"^(Inst|Conf) ({NAME}) (?:\[([^\]]+)\] )?\(({VERSION})(?: |\))"
)


class Blocked(Exception):
    def __init__(self, diagnostic):
        self.diagnostic = diagnostic


def valid(value, pattern):
    return isinstance(value, str) and pattern.fullmatch(value) is not None


def validate(request):
    if not isinstance(request, dict) or request.get("workspaceId") != WORKSPACE:
        raise ValueError("Invalid workspace.")
    action = request.get("action")
    fields = {
        "plan": {"workspaceId", "action", "operation"},
        "apply": {"workspaceId", "action", "operation", "operationId", "expectedPlanSha256"},
        "status": {"workspaceId", "action", "operationId"},
    }
    if not isinstance(action, str) or action not in fields or set(request) != fields[action]:
        raise ValueError("Invalid request.")
    if action != "status" and request["operation"] not in (REPAIR, BROWSER):
        raise ValueError("Invalid operation.")
    if action != "plan" and not valid(request["operationId"], UUID):
        raise ValueError("Invalid operation ID.")
    if action == "apply" and not valid(request["expectedPlanSha256"], SHA):
        raise ValueError("Invalid plan digest.")
    return request


def execute(args, *, mutate=False):
    # All executable paths and arguments are generated by this module.
    return subprocess.run(args, env=ENV, cwd="/", stdin=subprocess.DEVNULL,
                          stdout=subprocess.DEVNULL if mutate else subprocess.PIPE,
                          stderr=subprocess.DEVNULL, text=True, encoding="utf-8",
                          errors="replace", timeout=None if mutate else 20, check=False)


def parse_simulation(output):
    changes = []
    for line in output.splitlines():
        if line.startswith(("Remv ", "Purg ")):
            raise Blocked("unsafe_plan")
        if not line.startswith(("Inst ", "Conf ")):
            continue
        match = CHANGE.match(line)
        if not match:
            raise Blocked("unsafe_plan")
        verb, package, installed, version = match.groups()
        # No upgrades, downgrades or reinstalls; configuring already unpacked
        # packages is permitted only within the operation's fixed scope.
        if (verb == "Inst" and installed is not None) or len(package) > 150 or len(version) > 150:
            raise Blocked("unsafe_plan")
        changes.append({"action": "install" if verb == "Inst" else "configure",
                        "package": package, "version": version})
    if len(changes) > 100:
        raise Blocked("unsafe_plan")
    return changes


class Maintenance:
    def __init__(self, state=STATE, run=execute, dpkg_status=Path("/var/lib/dpkg/status")):
        self.state = state
        self.run = run
        self.dpkg_status = dpkg_status

    def result(self, status, operation=None, operation_id=None, **fields):
        result = {"status": status, **fields}
        if operation is not None:
            result["operation"] = operation
        if operation_id is not None:
            result["operationId"] = operation_id
        return result

    def state_digest(self):
        return hashlib.sha256(self.dpkg_status.read_bytes()).hexdigest()

    def healthy(self):
        check = self.run([APT, "-s", "check"])
        audit = self.run([DPKG, "--audit"])
        return check.returncode == 0 and audit.returncode == 0 and not audit.stdout.strip()

    def installed(self, package):
        result = self.run([QUERY, "-W", "-f=${db:Status-Abbrev} ${Version}", package])
        return result.stdout.strip().split() if result.returncode == 0 else []

    def command(self, operation, pins=()):
        base = [APT, *FLAGS]
        if operation == REPAIR:
            return [*base, "--fix-broken", "install", *pins]
        return [*base, "install", *LIBRARIES]

    def simulate(self, command):
        result = self.run([command[0], "-s", *command[1:]])
        if result.returncode != 0:
            raise Blocked("apt_simulation_failed")
        if len(result.stdout) > 512 * 1024:
            raise Blocked("unsafe_plan")
        return parse_simulation(result.stdout)

    def build_plan(self, operation):
        before = self.state_digest()
        if operation == BROWSER and not self.healthy():
            raise Blocked("apt_unhealthy")
        command = self.command(operation)
        changes = self.simulate(command)
        if operation == REPAIR:
            pins = []
            for change in changes:
                package, version = change["package"], change["version"]
                if not KERNEL.fullmatch(package):
                    raise Blocked("unsafe_plan")
                if change["action"] == "install":
                    match = MODULE.fullmatch(package)
                    if not match:
                        raise Blocked("unsafe_plan")
                    # Only restore modules matching an existing Oracle kernel.
                    # This is not a general package installer or kernel upgrade.
                    image = self.installed("linux-image-" + match[1] + "-oracle")
                    if len(image) != 2 or image[0] not in ("iU", "iF", "ii") or image[1] != version:
                        raise Blocked("unsafe_plan")
                    pins.append(package + "=" + version)
            command = self.command(operation, pins)
            if self.simulate(command) != changes:
                raise Blocked("unsafe_plan")
        if self.state_digest() != before:
            raise Blocked("plan_changed")
        plan = {"operation": operation, "dpkgSha256": before,
                "command": command, "changes": changes}
        digest = hashlib.sha256(json.dumps(plan, sort_keys=True, separators=(",", ":")).encode()).hexdigest()
        if not changes:
            if not self.healthy() or (operation == BROWSER and not self.libraries_installed()):
                raise Blocked("apt_unhealthy")
            return self.result("healthy", operation, planSha256=digest, changes=[]), command
        return self.result("ready", operation, planSha256=digest, changes=changes), command

    def libraries_installed(self):
        return all(self.installed(package)[:1] == ["ii"] for package in LIBRARIES)

    def path(self, operation_id):
        if not valid(operation_id, UUID):
            raise ValueError("Invalid operation ID.")
        return self.state / (operation_id + ".json")

    def read(self, operation_id):
        try:
            return json.loads(self.path(operation_id).read_text(encoding="utf-8"))
        except FileNotFoundError:
            return None

    def save(self, record):
        target = self.path(record["operationId"])
        temporary = target.with_suffix(".tmp")
        with temporary.open("w", encoding="utf-8") as output:
            json.dump(record, output, separators=(",", ":"))
            output.flush()
            os.fsync(output.fileno())
        os.replace(temporary, target)
        directory = os.open(self.state, os.O_DIRECTORY)
        try:
            os.fsync(directory)
        finally:
            os.close(directory)

    @staticmethod
    def public(record):
        return {key: value for key, value in record.items() if key != "createdAt"}

    @staticmethod
    def unit(operation_id):
        return "mcp-v3-apt-" + operation_id + ".service"

    def status(self, operation_id):
        record = self.read(operation_id)
        if record is None:
            return self.result("not_found", operation_id=operation_id)
        if record["status"] == "running" and time.time() - record["createdAt"] > 30:
            unit = self.run(["/usr/bin/systemctl", "show", "--property=ActiveState",
                             "--value", self.unit(operation_id)])
            record = self.read(operation_id)
            if record["status"] == "running" and (unit.returncode != 0 or
                    unit.stdout.strip() not in ("active", "activating", "reloading", "deactivating")):
                return {**self.public(record), "status": "outcome_unknown",
                        "diagnostic": "worker_unverified"}
        return self.public(record)

    def apply(self, request):
        operation, operation_id = request["operation"], request["operationId"]
        expected = request["expectedPlanSha256"]
        # Serializes launch decisions, not the long-lived systemd worker.
        with (self.state / "launch.lock").open("a") as lock:
            try:
                fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError:
                return self.result("blocked", operation, operation_id, diagnostic="apt_busy")
            prior = self.read(operation_id)
            if prior is not None:
                if prior["operation"] != operation or prior["planSha256"] != expected:
                    return self.result("operation_conflict", operation, operation_id,
                                       diagnostic="operation_conflict")
                return self.status(operation_id)
            for path in self.state.glob("*.json"):
                if self.read(path.stem)["status"] in ("running", "outcome_unknown"):
                    return self.result("blocked", operation, operation_id,
                                       diagnostic="another_operation_active")
            plan, _ = self.build_plan(operation)
            if plan["planSha256"] != expected:
                return self.result("plan_changed", operation, operation_id, diagnostic="plan_changed")
            if plan["status"] == "healthy":
                record = {**plan, "operationId": operation_id, "createdAt": time.time()}
                self.save(record)
                return self.public(record)
            record = {**plan, "status": "running", "operationId": operation_id, "createdAt": time.time()}
            self.save(record)  # Persist before the systemd side effect.
            launch = self.run(["/usr/bin/systemd-run", "--no-block", "--collect",
                               "--unit=" + self.unit(operation_id), "--property=Type=exec",
                               "--property=UMask=0077", "--", PYTHON, "-I", "-B", HELPER,
                               "--worker", operation_id])
            if launch.returncode != 0:
                # The request may have reached systemd. Leave the durable
                # receipt in place and reconcile the same ID, never redispatch.
                return {**self.public(record), "status": "outcome_unknown",
                        "diagnostic": "dispatch_unverified"}
            return self.public(record)

    def handle(self, request):
        request = validate(request)
        try:
            if request["action"] == "status":
                return self.status(request["operationId"])
            if request["action"] == "plan":
                return self.build_plan(request["operation"])[0]
            return self.apply(request)
        except Blocked as error:
            return self.result("blocked", request.get("operation"), request.get("operationId"),
                               diagnostic=error.diagnostic)

    def worker(self, operation_id):
        # A systemd transient unit is unique, and even a mistaken second
        # worker invocation must not run dpkg concurrently.
        with (self.state / "worker.lock").open("a") as lock:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
            self.run_worker(operation_id)

    def run_worker(self, operation_id):
        record = self.read(operation_id)
        if record is None or record["status"] != "running":
            raise ValueError("Worker requires an accepted operation.")
        try:
            plan, command = self.build_plan(record["operation"])
            if plan["planSha256"] != record["planSha256"] or plan["status"] != "ready":
                raise Blocked("plan_changed")
            # Rechecked immediately before execution; APT acquires its own
            # native package-manager lock. No broad upgrades/removals.
            command = [command[0], "-y", "-o", "DPkg::Lock::Timeout=0", *command[1:]]
            result = self.run(command, mutate=True)
            if result.returncode != 0:
                raise Blocked("apt_apply_failed")
            if not self.healthy() or (record["operation"] == BROWSER and not self.libraries_installed()):
                raise Blocked("postcheck_failed")
            record["status"] = "succeeded"
        except Blocked as error:
            record.update(status="failed", diagnostic=error.diagnostic)
        except Exception:
            record.update(status="outcome_unknown", diagnostic="worker_unverified")
        self.save(record)


def main():
    # This file is installed by an independent host administrator. It is not
    # a writable workspace script and has no general privileged shell mode.
    if os.geteuid() != 0:
        return 1
    state = STATE.lstat()
    if STATE.is_symlink() or not STATE.is_dir() or state.st_uid != 0 or state.st_mode & 0o077:
        return 1
    os.umask(0o077)
    service = Maintenance()
    if len(sys.argv) == 3 and sys.argv[1] == "--worker":
        service.worker(sys.argv[2])
        return 0
    if len(sys.argv) != 1:
        return 2
    try:
        raw = sys.stdin.buffer.read(8193)
        if len(raw) > 8192:
            return 2
        result = service.handle(json.loads(raw))
        print(json.dumps(result, separators=(",", ":")))
        return 0
    except Exception:
        # Do not return APT stderr, package configuration contents or secrets.
        return 1


if __name__ == "__main__":
    sys.exit(main())
